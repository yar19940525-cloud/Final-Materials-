export function analysisSmsPrompt(analysis: string, note: string): string {
  return `너는 학원 영어 선생님이야. 아래 [이번 기출분석 자료]를 바탕으로, 학생·학부모에게 보낼 기출분석 요약 문자를 [예시]와 똑같은 형식·기호·말투로 새로 써 줘.

[예시]
${EXAMPLE}

[이번 기출분석 자료]
${analysis}

규칙:
- 첫 줄: ■ 연도 학년(M1=중1, M2=중2, M3=중3, H1=고1…) 학교 이름 학기 시험 종류 기출 분석 ■ (예시와 같은 모양, 값은 이번 자료에서)
- 1. 총 문항 수와 난이도 [상/중/하], 선택형 : 서술형 문항 수와 비율(%), 범위.
- 2. "(이번 시험 종류) 분석 ★이번 시험의 가장 큰 특징★" 다음, 파트별(대화문·본문·어법·어휘 등 이번 시험에 실제 있는 파트) "▶ ○○ 파트 (n문항, n%): ★핵심★ 설명" 한 줄씩. 문항 수와 비율은 자료와 맞게 계산하고, 비율 합이 100%가 되게.
- 3. 오답률이 높았던 문항: 실제 오답률 자료가 없으면 자료에서 가장 어렵거나 함정이 있던 문항 3~4개를 골라 "▶ 선택형 n번 [유형] 이유" / "▶ 서술형 n …" 형식으로.
- 4.특이 사항: ▶ 2개 내외. 5. 다음 지필고사 대비 전략: ♡ 3개 내외. 마지막 줄은 예시처럼 ♥…♥ 인사.
- 예시의 내용(안화중·과거형 등)을 그대로 쓰지 말고 전부 이번 자료 내용으로. 자료에 없는 사실은 지어내지 마.
- 마크다운(**, #)·코드블록 금지. 문자 내용만 출력하고 앞뒤 설명은 쓰지 마.
${note ? `- 선생님 추가 요청 (최우선 반영): ${note}` : ""}`;
}
